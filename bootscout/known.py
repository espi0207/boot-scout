_COMPILED = [(re.compile(k.pattern, re.I), k) for k in KNOWN]


def match(*texts: str) -> Known | None:
    """El primero de la lista que encaja con alguno de los textos (orden, nombre, ruta)."""
    for pattern, known in _COMPILED:
        if any(text and pattern.search(text) for text in texts):
            return known
    return None
